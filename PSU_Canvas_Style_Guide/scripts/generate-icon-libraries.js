#!/usr/bin/env node
// Regenerates the icon library JS files from the collection directories so the
// local folders, the generated libraries, and the GitHub repo can't drift.
//
// Usage: node scripts/generate-icon-libraries.js   (run from the project root)
//
// Collections:
//   General      assets/icons/collections/General/{Dark,Light}   -> general-icon-library.js
//   Icon Banners assets/icons/collections/Icon Banners/{Color,Dark,Light} -> icon-banners-icon-library.js

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

// ---------------------------------------------------------------------------
// General icon categories: first matching keyword rule wins.
// ---------------------------------------------------------------------------
const GENERAL_CATEGORY_RULES = [
  ['Navigation & Arrows', ['arrow', 'chevron', 'expand', 'collapse', 'move', 'drag', 'sort', 'hamburger', 'menu', 'home', 'exit', 'external', 'launch', 'refresh', 'reply', 'replied', 'undo', 'redo', 'back', 'forward', 'next', 'prev']],
  ['Media & AV', ['video', 'audio', 'mic', 'camera', 'play', 'pause', 'record', 'film', 'movie', 'music', 'sound', 'volume', 'media', 'image', 'photo', 'picture', 'gallery', 'youtube', 'vimeo', 'kaltura', 'studio', 'closed-caption', 'subtitles', 'attach-media']],
  ['Files & Documents', ['file', 'folder', 'document', 'doc', 'pdf', 'page', 'paper', 'archive', 'download', 'upload', 'export', 'import', 'copy', 'paste', 'clipboard', 'print', 'save', 'zip', 'attach']],
  ['People & Communication', ['user', 'person', 'people', 'group', 'student', 'teacher', 'instructor', 'profile', 'account', 'address-book', 'email', 'mail', 'message', 'chat', 'discussion', 'comment', 'conversation', 'announcement', 'megaphone', 'share', 'community', 'collaborat']],
  ['Courses & Grading', ['assignment', 'quiz', 'rubric', 'grade', 'gradebook', 'module', 'course', 'syllabus', 'outcome', 'mastery', 'certif', 'award', 'trophy', 'medal', 'graduation', 'book', 'education', 'learn', 'lesson', 'lti', 'canvas', 'peer', 'review', 'check-mark', 'complete', 'lightbulb']],
  ['Time & Planning', ['calendar', 'clock', 'timer', 'time', 'schedule', 'date', 'deadline', 'event', 'reminder', 'hourglass', 'history']],
  ['Editing & Tools', ['edit', 'pencil', 'pen', 'highlight', 'text', 'font', 'bold', 'italic', 'underline', 'strikethrough', 'align', 'indent', 'list', 'bullet', 'number', 'table', 'link', 'unlink', 'crop', 'paint', 'brush', 'ruler', 'scissors', 'tool', 'settings', 'gear', 'configure', 'wrench', 'admin', 'integration', 'plug']],
  ['Status & Alerts', ['check', 'warning', 'alert', 'error', 'info', 'question', 'help', 'flag', 'star', 'heart', 'like', 'thumbs', 'lock', 'unlock', 'eye', 'visible', 'hidden', 'mute', 'ban', 'no-', 'stop', 'trouble', 'shield', 'privacy', 'success', 'progress', 'empty', 'off', 'on']]
];

function categorizeGeneralIcon(slug) {
  const haystack = slug.toLowerCase();
  for (const [category, keywords] of GENERAL_CATEGORY_RULES) {
    if (keywords.some((keyword) => haystack.includes(keyword))) return category;
  }
  return 'Other';
}

function prettifyGeneralLabel(slug) {
  let label = slug
    .split('-')
    .map((word) => (/^\d/.test(word) ? word : word.charAt(0).toUpperCase() + word.slice(1)))
    .join(' ');
  const acronyms = { 'A11y': 'A11y', ' Ai': ' AI', ' Pdf': ' PDF', ' Lti': ' LTI', ' Sis': ' SIS', ' Rss': ' RSS', ' Id': ' ID' };
  label = label.replace(/^Ai\b/, 'AI');
  Object.entries(acronyms).forEach(([from, to]) => {
    label = label.split(from).join(to);
  });
  return label;
}

function listPngs(dir) {
  return fs.readdirSync(dir).filter((file) => file.toLowerCase().endsWith('.png')).sort();
}

function assertVariantsMatch(baseDir, baseVariant, variants, files) {
  variants.forEach((variant) => {
    const variantDir = path.join(baseDir, variant);
    if (!fs.existsSync(variantDir)) {
      console.warn(`WARNING: ${variantDir} does not exist locally. Inserts for that variant rely on the GitHub repo copy.`);
      return;
    }
    const variantFiles = new Set(listPngs(variantDir));
    const missing = files.filter((file) => !variantFiles.has(file));
    if (missing.length) {
      console.warn(`WARNING: ${variant} is missing ${missing.length} file(s) present in ${baseVariant}: ${missing.slice(0, 5).join(', ')}${missing.length > 5 ? '…' : ''}`);
    }
  });
}

function writeLibrary(outFile, globalName, entries, comment) {
  const body = `// ${comment}\n// Generated by scripts/generate-icon-libraries.js — do not edit by hand.\nwindow.${globalName} = ${JSON.stringify(entries, null, 2)};\n\nwindow.CEI_SVG_ICON_LIBRARY = (window.CEI_SVG_ICON_LIBRARY || []).concat(window.${globalName});\n`;
  fs.writeFileSync(path.join(ROOT, outFile), body);
  console.log(`${outFile}: ${entries.length} entries`);
}

// --- General ---------------------------------------------------------------
const generalDir = path.join(ROOT, 'assets/icons/collections/General');
const generalFiles = listPngs(path.join(generalDir, 'Dark'));
assertVariantsMatch(generalDir, 'Dark', ['Light'], generalFiles);

const generalEntries = generalFiles.map((file) => {
  const slug = file.replace(/^icon-/, '').replace(/\.png$/i, '');
  return {
    key: `general-${slug}`,
    label: prettifyGeneralLabel(slug),
    path: `assets/icons/collections/General/Dark/${file}`,
    collection: 'general',
    category: categorizeGeneralIcon(slug),
    type: 'png'
  };
});
writeLibrary('general-icon-library.js', 'CEI_GENERAL_ICON_LIBRARY', generalEntries,
  'General icon collection (Dark/Light PNG variants). Path points at Dark; Light lives in ../Light/ with the same filename.');

// --- Icon Banners ----------------------------------------------------------
const bannersDir = path.join(ROOT, 'assets/icons/collections/Icon Banners');
const bannerFiles = listPngs(path.join(bannersDir, 'Color'));
assertVariantsMatch(bannersDir, 'Color', ['Dark', 'Light'], bannerFiles);

const bannerEntries = bannerFiles.map((file) => {
  const name = file.replace(/\.png$/i, '');
  const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  return {
    key: `icon-banners-${slug}`,
    label: name,
    path: `assets/icons/collections/Icon Banners/Color/${file}`,
    collection: 'icon-banners',
    category: 'Icon Banners',
    type: 'png'
  };
});
writeLibrary('icon-banners-icon-library.js', 'CEI_ICON_BANNERS_LIBRARY', bannerEntries,
  'Icon Banners collection (Color/Dark/Light PNG variants). Path points at Color; Dark and Light live in sibling directories with the same filename.');

// --- Fill Icons ------------------------------------------------------------
// Single "Color" variant; categories come from the subfolder names.
const fillDir = path.join(ROOT, 'assets/icons/collections/Fill Icons');
const fillEntries = [];
fs.readdirSync(fillDir)
  .filter((entry) => fs.statSync(path.join(fillDir, entry)).isDirectory())
  .sort()
  .forEach((subfolder) => {
    listPngs(path.join(fillDir, subfolder)).forEach((file) => {
      const name = file.replace(/\.png$/i, '');
      const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
      fillEntries.push({
        key: `fill-icons-${slug}`,
        label: name,
        path: `assets/icons/collections/Fill Icons/${subfolder}/${file}`,
        collection: 'fill-icons',
        category: subfolder,
        type: 'png'
      });
    });
  });
writeLibrary('fill-icons-icon-library.js', 'CEI_FILL_ICONS_LIBRARY', fillEntries,
  'Fill Icons collection (Color PNGs). Categories mirror the subfolder names.');

console.log('Done. Remember to push any new/changed PNGs to the psu-cei/ccbe GitHub repo — inserted HTML loads them from there.');
